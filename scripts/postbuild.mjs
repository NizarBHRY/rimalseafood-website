// Runs after `astro build`:
//  1. Copies the pages that still come from the earlier site (site/) into
//     dist/: the staff dashboard (manage.html) and the printable menu.
//  2. Writes dist/_headers with a Content-Security-Policy that allows exactly
//     the inline scripts in the built pages (by sha256 hash), so the policy
//     can't drift out of date when a page changes.
import { createHash } from 'node:crypto';
import { cpSync, existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const root = process.cwd();
const site = join(root, 'site');
const dist = join(root, 'dist');

// ---------- 1. Earlier-site pages ----------
const LEGACY = [
  'manage.html', 'admin.js', 'app.js', 'config.js', 'menu-data.js',
  'rimal-menu.html', 'rimal-menu.js', 'menu-corrections.js',
  'rimal-logo.jpg', 'rimal-mark.webp', 'rimal-menu-qr.png',
  '.well-known/security.txt',
];
for (const f of LEGACY) {
  const from = join(site, f);
  if (!existsSync(from)) throw new Error(`postbuild: missing site/${f}`);
  if (existsSync(join(dist, f)) && !f.startsWith('.well-known')) throw new Error(`postbuild: dist/${f} already exists; refusing to overwrite`);
  cpSync(from, join(dist, f));
}
// Pages saved from the live site can carry Netlify's preview toolbar tag.
for (const f of LEGACY.filter((x) => x.endsWith('.html'))) {
  const p = join(dist, f);
  writeFileSync(p, readFileSync(p, 'utf8').replace(/\s*<script[^>]*\/\.netlify\/scripts\/hud[^>]*><\/script>/g, ''));
}

// ---------- 2. Headers ----------
function* htmlFiles(dir) {
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, e.name);
    if (e.isDirectory()) yield* htmlFiles(p);
    else if (e.name.endsWith('.html')) yield p;
  }
}
const hashes = new Set();
const SCRIPT = /<script(?![^>]*\bsrc=)([^>]*)>([\s\S]*?)<\/script>/gi;
for (const file of htmlFiles(dist)) {
  for (const [, attrs, body] of readFileSync(file, 'utf8').matchAll(SCRIPT)) {
    if (/type=["']?application\/(ld\+)?json/i.test(attrs) || !body.trim()) continue;
    hashes.add(`'sha256-${createHash('sha256').update(body, 'utf8').digest('base64')}'`);
  }
}

const SUPABASE = 'https://efdclcbhsvlnvmjfqnin.supabase.co';
const csp = [
  "default-src 'self'",
  `script-src 'self' https://cdn.jsdelivr.net/npm/@supabase/supabase-js@2.117.3/ ${[...hashes].sort().join(' ')}`,
  "style-src 'self' 'unsafe-inline' https://fonts.googleapis.com",
  "font-src 'self' https://fonts.gstatic.com",
  `img-src 'self' data: blob: https://images.unsplash.com ${SUPABASE}`,
  `connect-src 'self' ${SUPABASE} wss://efdclcbhsvlnvmjfqnin.supabase.co`,
  'frame-src https://www.google.com https://maps.google.com',
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  "frame-ancestors 'none'",
  'upgrade-insecure-requests',
].join('; ');

const headers = `# Generated by scripts/postbuild.mjs. Do not edit dist/_headers by hand.
/*
  Strict-Transport-Security: max-age=31536000; includeSubDomains
  X-Content-Type-Options: nosniff
  X-Frame-Options: DENY
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=(), usb=()
  Content-Security-Policy: ${csp}

# Staff-only pages: never in search results.
/manage*
  X-Robots-Tag: noindex, nofollow
/data-version.txt
  X-Robots-Tag: noindex
  Cache-Control: no-cache

# Astro's hashed build files never change, so browsers may keep them a year.
/_astro/*
  Cache-Control: public, max-age=31536000, immutable

/rimal-logo.webp
  Cache-Control: public, max-age=604800
/rimal-logo-240.webp
  Cache-Control: public, max-age=604800
/rimal-mark.webp
  Cache-Control: public, max-age=604800
/rimal-icon-180.png
  Cache-Control: public, max-age=604800
/rimal-menu-qr.png
  Cache-Control: public, max-age=604800
`;
writeFileSync(join(dist, '_headers'), headers);
console.log(`postbuild: copied ${LEGACY.length} earlier-site files, ${hashes.size} inline script hashes -> ${relative(root, join(dist, '_headers'))}`);
